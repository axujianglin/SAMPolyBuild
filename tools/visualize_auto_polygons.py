"""Render SAMPoly Auto polygons on one source image in a single canvas.

This utility consumes the existing COCO-style ``results.json`` written by
``infer_auto.py``.  It does not load a model, alter predictions, or depend on
the Tile Workflow.  The plotting code is separated from result parsing so the
geometry rules can be tested without opening a GUI window.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any


def parse_args() -> argparse.Namespace:
    """Parse paths and display options for a single-image overlay."""
    parser = argparse.ArgumentParser(
        description="Overlay SAMPoly Auto polygons on one image in a single canvas."
    )
    parser.add_argument("--image", required=True, help="Source image path.")
    parser.add_argument(
        "--results",
        required=True,
        help="COCO-style results.json generated by infer_auto.py.",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Output PNG path; defaults beside results.json.",
    )
    parser.add_argument(
        "--score-threshold",
        type=float,
        default=0.1,
        help="Draw predictions whose score is at least this value.",
    )
    parser.add_argument("--line-color", default="red", help="Matplotlib polygon color.")
    parser.add_argument(
        "--line-width", type=float, default=1.5, help="Polygon line width in points."
    )
    parser.add_argument("--dpi", type=int, default=200, help="Saved PNG resolution.")
    parser.add_argument(
        "--show",
        action="store_true",
        help="Open an interactive Matplotlib window after saving the overlay.",
    )
    return parser.parse_args()


def load_auto_results(results_path: Path) -> list[dict[str, Any]]:
    """Load and validate the top-level Auto result collection."""
    path = Path(results_path).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(f"Auto results file not found: {path}")
    try:
        with path.open("r", encoding="utf-8") as stream:
            payload = json.load(stream)
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid JSON in Auto results file {path}: {exc}") from exc
    if not isinstance(payload, list):
        raise ValueError("Auto results JSON root must be a list.")
    for index, item in enumerate(payload):
        if not isinstance(item, dict):
            raise ValueError(f"Auto result at index {index} must be an object.")
    return payload


def _result_matches_image(result_image_id: Any, image_stem: str) -> bool:
    """Match direct-inference ids, including ids that retain subdirectories."""
    result_name = Path(str(result_image_id)).name
    return result_name == image_stem


def _normalize_rings(segmentation: Any, result_index: int) -> list[list[list[float]]]:
    """Convert a COCO flat ring or list of rings into validated point pairs."""
    if not isinstance(segmentation, list) or not segmentation:
        raise ValueError(f"Result {result_index} has an empty or invalid segmentation.")
    raw_rings = segmentation if isinstance(segmentation[0], list) else [segmentation]
    rings: list[list[list[float]]] = []
    for ring_index, raw_ring in enumerate(raw_rings):
        if not isinstance(raw_ring, list) or len(raw_ring) < 6 or len(raw_ring) % 2:
            raise ValueError(
                f"Result {result_index} ring {ring_index} must contain at least "
                "three x/y pairs."
            )
        try:
            values = [float(value) for value in raw_ring]
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f"Result {result_index} ring {ring_index} contains non-numeric coordinates."
            ) from exc
        if not all(math.isfinite(value) for value in values):
            raise ValueError(
                f"Result {result_index} ring {ring_index} contains NaN or Inf coordinates."
            )
        rings.append(
            [[values[offset], values[offset + 1]] for offset in range(0, len(values), 2)]
        )
    return rings


def select_polygon_rings(
    results: list[dict[str, Any]],
    image_stem: str,
    score_threshold: float,
) -> tuple[list[list[list[float]]], int]:
    """Select one image's predictions and return all valid polygon rings."""
    if not 0.0 <= float(score_threshold) <= 1.0:
        raise ValueError("--score-threshold must be between 0 and 1.")

    matching_results = [
        (index, result)
        for index, result in enumerate(results)
        if _result_matches_image(result.get("image_id", ""), image_stem)
    ]
    if results and not matching_results:
        available_ids = sorted({str(result.get("image_id", "")) for result in results})
        raise ValueError(
            f"No Auto results match image stem {image_stem!r}. "
            f"Available image_id values: {available_ids}"
        )

    rings: list[list[list[float]]] = []
    accepted_predictions = 0
    for result_index, result in matching_results:
        raw_score = result.get("score", result.get("score_cls", 0.0))
        try:
            score = float(raw_score)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Result {result_index} has a non-numeric score.") from exc
        if not math.isfinite(score):
            raise ValueError(f"Result {result_index} has a non-finite score.")
        if score < score_threshold:
            continue
        rings.extend(_normalize_rings(result.get("segmentation"), result_index))
        accepted_predictions += 1
    return rings, accepted_predictions


def render_overlay(
    image_path: Path,
    rings: list[list[list[float]]],
    output_path: Path,
    *,
    line_color: str = "red",
    line_width: float = 1.5,
    dpi: int = 200,
    show: bool = False,
) -> Path:
    """Draw all rings over one image, save one PNG, and optionally show it."""
    image_path = Path(image_path).expanduser().resolve()
    output_path = Path(output_path).expanduser().resolve()
    if not image_path.is_file():
        raise FileNotFoundError(f"Source image not found: {image_path}")
    if line_width <= 0:
        raise ValueError("--line-width must be greater than zero.")
    if dpi <= 0:
        raise ValueError("--dpi must be greater than zero.")

    # Select a non-interactive backend before importing pyplot on headless Linux.
    import matplotlib

    if not show:
        matplotlib.use("Agg", force=True)
    import matplotlib.pyplot as plt
    import numpy as np

    image = plt.imread(image_path)
    figure, axis = plt.subplots(figsize=(12, 12))
    axis.imshow(image)
    for ring in rings:
        points = np.asarray(ring, dtype=float)
        closed = np.vstack([points, points[0]])
        axis.plot(
            closed[:, 0],
            closed[:, 1],
            color=line_color,
            linewidth=line_width,
            alpha=0.9,
        )
    axis.axis("off")
    figure.tight_layout(pad=0)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output_path, dpi=dpi, bbox_inches="tight", pad_inches=0)
    if show:
        plt.show()
    plt.close(figure)
    return output_path


def run(args: argparse.Namespace) -> dict[str, Any]:
    """Validate CLI values, render the overlay, and return a stable summary."""
    image_path = Path(args.image).expanduser().resolve()
    results_path = Path(args.results).expanduser().resolve()
    output_path = (
        Path(args.output).expanduser().resolve()
        if args.output
        else results_path.parent / f"{image_path.stem}_polygon_overlay.png"
    )
    results = load_auto_results(results_path)
    rings, prediction_count = select_polygon_rings(
        results,
        image_path.stem,
        float(args.score_threshold),
    )
    saved_path = render_overlay(
        image_path,
        rings,
        output_path,
        line_color=args.line_color,
        line_width=float(args.line_width),
        dpi=int(args.dpi),
        show=bool(args.show),
    )
    summary = {
        "image": str(image_path),
        "matched_predictions": prediction_count,
        "polygon_rings": len(rings),
        "output": str(saved_path),
    }
    print(f"Image: {summary['image']}")
    print(f"Matched predictions: {summary['matched_predictions']}")
    print(f"Polygon rings: {summary['polygon_rings']}")
    print(f"Saved overlay: {summary['output']}")
    return summary


def main() -> int:
    """CLI entry point with one explicit failure message."""
    try:
        run(parse_args())
    except Exception as exc:
        print(f"Auto polygon visualization failed: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
